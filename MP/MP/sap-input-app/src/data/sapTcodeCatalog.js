// Defensive deduplicator when callers supply custom or raw catalog arrays.
export function dedupeSapTcodeCatalog(rawItems = SAP_TCODE_CATALOG) {
  const seen = new Set();
  const cleaned = [];

  for (const raw of rawItems) {
    if (!raw) continue;
    const isDoc = raw.type === 'document' || (raw.fileName || raw.code || '').toLowerCase().endsWith('.docx');
    const uniqueKey = isDoc
      ? `doc:${String(raw.fileName || raw.description || raw.code).trim().toLowerCase()}`
      : `tcode:${String(raw.code || raw.id).trim().toUpperCase()}`;

    if (seen.has(uniqueKey)) continue;
    seen.add(uniqueKey);

    cleaned.push({
      ...raw,
      type: isDoc ? 'document' : 'tcode',
      code: isDoc ? 'DOCX' : String(raw.code || raw.id).trim().toUpperCase(),
    });
  }

  return cleaned;
}
